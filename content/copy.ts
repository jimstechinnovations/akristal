// Every piece of wording (and section photo) on the public pages, with its default.
// Admin → Website text shows one form per page built from this list; a saved value
// replaces the default, and clearing a field brings the default back.
// Text can include {placeholders} that the page fills with live figures, e.g. {minDeposit}.
// Shared by server and client: no server-only imports.

export type CopySubField = { name: string; label: string; type: 'text' | 'textarea' }
export type CopyField =
  | { name: string; label: string; type: 'text' | 'textarea' | 'image'; default: string; help?: string }
  | { name: string; label: string; type: 'list'; itemLabel: string; fields: CopySubField[]; default: Record<string, string>[]; help?: string }

export type CopyPage = { key: string; title: string; description: string; paths: string[]; fields: CopyField[] }

const text = (name: string, label: string, value: string, help?: string): CopyField => ({ name, label, type: value.length > 90 ? 'textarea' : 'text', default: value, help })
const image = (name: string, label: string, value: string): CopyField => ({ name, label, type: 'image', default: value, help: 'Wide photo, at least 1600 pixels across.' })
const steps = (name: string, label: string, value: { title: string; text: string }[]): CopyField => ({
  name,
  label,
  type: 'list',
  itemLabel: 'item',
  fields: [
    { name: 'title', label: 'Title', type: 'text' },
    { name: 'text', label: 'Text', type: 'textarea' },
  ],
  default: value,
})
const lines = (name: string, label: string, value: string[]): CopyField => ({
  name,
  label,
  type: 'list',
  itemLabel: 'line',
  fields: [{ name: 'text', label: 'Text', type: 'textarea' }],
  default: value.map((t) => ({ text: t })),
})
const faqs = (name: string, label: string, value: { q: string; a: string }[]): CopyField => ({
  name,
  label,
  type: 'list',
  itemLabel: 'question',
  fields: [
    { name: 'q', label: 'Question', type: 'text' },
    { name: 'a', label: 'Answer', type: 'textarea' },
  ],
  default: value,
})

